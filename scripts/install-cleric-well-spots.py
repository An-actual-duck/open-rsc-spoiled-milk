#!/usr/bin/env python3
"""Append a game-owned invisible interaction footprint, preserving existing native records."""
import argparse,hashlib,importlib.util,json,struct
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
spec=importlib.util.spec_from_file_location('native',ROOT/'scripts/import-native-scenery.py');native=importlib.util.module_from_spec(spec);spec.loader.exec_module(native)
sha=lambda b:hashlib.sha256(b).hexdigest()
def main():
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
 # Native negative-Y-up quad, centered on one tile. Inset edges avoid neighboring
 # hit footprints, four-unit clearance avoids z-fighting with its liquid floor.
 vertices=[(-60,-4,-60),(60,-4,-60),(60,-4,60),(-60,-4,60)]
 model=struct.pack('>HH',4,1)+b''.join(struct.pack('>hhhh',*(v[axis] for v in vertices)) for axis in range(3))
 model+=bytes([4])+struct.pack('>hh',32767,32767)+bytes([0,0,1,2,3])
 archive=ROOT/'Client_Base/Cache/video/models.orsc';data=archive.read_bytes();entries=native.archive_entries(data);key=native.name_hash('interaction_spot.ob3')
 owned=[(h,payload) for h,payload in entries if int.from_bytes(h[:4],'big')==key]
 manifest=ROOT/'dev/myworld/cleric-wells/interaction-spots.json'
 if not owned:
  assert not a.check,'Missing interaction footprint'
  original={h.hex():sha(payload) for h,payload in entries};assert len(original)==len(entries)
  baseline=sha(data);archive.write_bytes(native.append_model(data,'interaction_spot.ob3',model))
 else:
  assert len(owned)==1 and owned[0][1]==model,'Existing footprint differs; explicit review required'
  previous=json.loads(manifest.read_text());original=previous['preservedNativeRecords'];baseline=previous['sourceArchiveSha256']
 now=native.archive_entries(archive.read_bytes());assert {(h.hex()):sha(payload) for h,payload in now if int.from_bytes(h[:4],'big')!=key}==original
 result={'status':'Authoring and clickable preview only; charging intentionally deferred by owner','sourceArchiveSha256':baseline,'model':'interaction_spot.ob3','modelSha256':sha(model),'vertices':vertices,'faces':1,'frontAndBack':'native transparent sentinel32767','objectIds':{'ichor':1354,'divineWater':1355},'preservedNativeRecords':original,'noExternalAssetSource':'Authored primitive quad generated by this script; no third-party asset copied'}
 encoded=json.dumps(result,indent=2)+'\n'
 if a.check:assert manifest.read_text()==encoded
 else:manifest.write_text(encoded)
 print('PASS shared native transparent footprint; %d existing native records byte-exact; only one new model'%len(original))
if __name__=='__main__':main()
