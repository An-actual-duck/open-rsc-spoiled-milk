#!/usr/bin/env python3
"""Game-owned coating catalog/art generator. One explicit manifest; no editor roster."""
import argparse, gzip, hashlib, importlib.util, json, struct, subprocess
from pathlib import Path
from PIL import Image

ROOT=Path(__file__).resolve().parents[1]
SPEC=ROOT/'dev/myworld/battleaxe-coatings/manifest.json'
spec=importlib.util.spec_from_file_location('coating_art',ROOT/'scripts/audit-battleaxe-coatings.py')
art=importlib.util.module_from_spec(spec);spec.loader.exec_module(art)

def archive(data):
    """Retain every untouched serialized entry byte, including its original palette."""
    pos=1;groups=[]
    def string():
        nonlocal pos
        end=data.index(0,pos);s=data[pos:end].decode('latin1');pos=end+1;return s
    for _ in range(data[0]):
        name=string();count=struct.unpack_from('>H',data,pos)[0];pos+=2;entries=[]
        for _ in range(count):
            start=pos;entry=string();kind=data[pos];pos+=1
            if kind in (1,2,3):pos+=1
            frames=data[pos];colours=data[pos+1]+1;pos+=2+colours*3
            for _ in range(frames):
                w,h=struct.unpack_from('>HH',data,pos);pos+=13+w*h
            entries.append((entry,data[start:pos]))
        groups.append((name,entries))
    assert pos==len(data)
    return groups

def main():
    ap=argparse.ArgumentParser();ap.add_argument('--check',action='store_true');args=ap.parse_args()
    m=json.loads(SPEC.read_text());variants=m['variants'];assert len(variants)==15
    def emit(path,data):
        p=ROOT/path
        if isinstance(data,str):data=data.encode()
        if args.check:assert p.read_bytes()==data,str(path)
        else:p.parent.mkdir(parents=True,exist_ok=True);p.write_bytes(data)
    defs={}
    for f in ['ItemDefs.json','ItemDefsCustom.json','ItemDefsMyWorld.json']:
        data=json.loads((ROOT/'server/conf/server/defs'/f).read_text())
        for row in data.get('item',data.get('items',[])):defs.setdefault(row['id'],{}).update(row)
    roster={i for i,d in defs.items() if 'battle axe' in d.get('name','').lower() or 'battleaxe' in d.get('name','').lower()}
    assert roster=={v['baseId'] for v in variants},roster
    assert not (set(defs)&set(range(3410,3426))), 'Coating IDs collide with existing items'
    base=defs[165];item=dict(base,id=m['coatingId'],name='Viscous weapon coating',description='One single-use dose. Coat one battleaxe with accumulating Slow and weaker poison.',command='',basePrice=m['price'])
    # Use an inert potion template; explicitly remove inherited equipment fields.
    item.update(isWearable=0,wearSlot=-1,wearableID=0,appearanceID=0,isStackable=0,isNoteable=1,isUntradable=0)
    rows=[item]
    client=['// Generated by scripts/generate-battleaxe-coatings.py; edit the manifest.','package com.openrsc.client.entityhandling;', 'import com.openrsc.client.entityhandling.defs.*;', 'import java.util.List;', 'public final class BattleaxeCoatingDefinitions {',' private BattleaxeCoatingDefinitions() {}',' public static ItemDef[] items() { return new ItemDef[] {']
    client.append('  new ItemDef("Viscous weapon coating","One single-use dose. Coat one battleaxe with accumulating Slow and weaker poison.","",300,-1,"external-png:viscous-coating",false,false,0,0,false,false,true,3410),')
    mapping=[]
    for v in variants:
        d=dict(defs[v['baseId']]);d.update(id=v['coatedId'],name='Viscous '+d['name'],description='Adds 4 accumulating Slow power (cap 12) and weaker weapon poison. Wipe clean to remove; no refund.',command='Wipe clean',appearanceID=v['appearanceId'],basePrice=d['basePrice']+m['price']);rows.append(d)
        client.append('  new ItemDef(%s,%s,"Wipe clean",%d,-1,"external-png:viscous-battleaxe-%d",false,true,%d,0,%s,%s,%s,%d),'%(json.dumps(d['name']),json.dumps(d['description']),d['basePrice'],v['baseId'],d['wearableID'],str(bool(d['isMembersOnly'])).lower(),str(bool(d['isUntradable'])).lower(),str(bool(d.get('isNoteable',0))).lower(),d['id']))
        mapping.append('  {%d,%d,%d},'%(v['baseId'],v['coatedId'],v['tier']))
    client+=[' }; }',' public static void animations(List<AnimationDef> animations) {','  while(animations.size()<%d) animations.add(new AnimationDef("battleaxe","equipment",0xFFFFFF,0,true,false,0));'%m['appearanceStart'],'  if(animations.size()!=%d) throw new IllegalStateException("Coating animation tail changed; regenerate reviewed IDs");'%m['appearanceStart']]
    for v in variants:client.append('  animations.add(new AnimationDef("viscousbattleaxe","equipment",%d,0,true,false,0));'%v['heldMask'])
    client+=[' }','}']
    emit('Client_Base/src/com/openrsc/client/entityhandling/BattleaxeCoatingDefinitions.java','\n'.join(client)+'\n')
    emit('server/conf/server/defs/BattleaxeCoatingItemDefs.json',json.dumps({'items':rows},indent=2)+'\n')
    emit('server/src/com/openrsc/server/content/coatings/BattleaxeCoatingCatalog.java','''// Generated by scripts/generate-battleaxe-coatings.py; edit the manifest.
package com.openrsc.server.content.coatings;
public final class BattleaxeCoatingCatalog {
 public static final int COATING=3410;
 private static final int[][] ROWS={
'''+ '\n'.join(mapping)+'''
 };
 private BattleaxeCoatingCatalog() {}
 public static int coated(int base){for(int[] r:ROWS)if(r[0]==base)return r[1];return -1;}
 public static int base(int coated){for(int[] r:ROWS)if(r[1]==coated)return r[0];return coated;}
 public static boolean isCoated(int id){return base(id)!=id;}
 public static int tier(int id){for(int[] r:ROWS)if(r[1]==id)return r[2];return 0;}
}
''')
    # The reviewed Phase1 edge transform operates on native pixels only.
    custom=ROOT/'Client_Base/Cache/video/Custom_Sprites.osar';entries=art.archive_entries(custom)
    rawframes=entries['equipment','battleaxe']['frames'];held=[]
    assetroot=Path('dev/myworld/assets/sprites/items/inventory-ground')
    authored=Path('dev/myworld/battleaxe-coatings/art')
    images={}
    for v in variants:
        raw=entries['items','272' if v['baseId']==2752 else '84']['frames'][0][0]
        images[assetroot/f"viscous-battleaxe-{v['baseId']}.png"]=art.edge_candidate(art.recolor(raw,v['inventoryMask']),raw,v['baseId']==2752)[0]
    bottle=Image.open(ROOT/'dev/myworld/reference-library/items/consumables/potions-and-bottles/id-02202.png').convert('RGBA')
    # One full single-use container: no obsolete three-dose fill-band semantics.
    p=bottle.load()
    for y in range(bottle.height):
        for x in range(bottle.width):
            r,g,b,a=p[x,y]
            if a and g>r*1.2 and g>b*1.2:p[x,y]=(14,max(50,g*180//255),max(45,g*166//255),a)
    images[assetroot/'viscous-coating.png']=bottle
    for n,(raw,meta) in enumerate(rawframes):
        im=art.edge_candidate(raw,raw)[0];held.append((im,meta));images[Path('dev/myworld/assets/sprites/equipment/viscousbattleaxe')/f'held-{n:02}.png']=im
    for path,im in images.items():
        import io
        buf=io.BytesIO();im.save(buf,format='PNG');emit(path,buf.getvalue())
    # Encode a new native family; original frame geometry/shift/offset are exact.
    palette=[(0,0,0)];framepixels=[]
    for im,meta in held:
        w,h=meta['crop'];x,y=meta['offset'] if meta['shift'] else (0,0);pixels=[]
        for yy in range(h):
            for xx in range(w):
                r,g,b,a=im.getpixel((xx+x,yy+y));rgb=(r,g,b) if a else (0,0,0)
                if rgb not in palette:palette.append(rgb)
                pixels.append(palette.index(rgb))
        framepixels.append(bytes(pixels))
    assert len(palette)<=256
    entry=b'viscousbattleaxe\0'+bytes([entries['equipment','battleaxe']['kind'],3,18,len(palette)-1])+bytes(c for rgb in palette for c in rgb)
    for (_,meta),pixels in zip(held,framepixels):
        entry+=struct.pack('>HHBhhHH',*meta['crop'],int(meta['shift']),*meta['offset'],*meta['canvas'])+pixels
    preservation={}
    for name in ['Custom_Sprites.osar']:
        path=ROOT/'Client_Base/Cache/video'/name;groups=archive(gzip.decompress(path.read_bytes()));before={}
        for group,items in groups:
            for key,blob in items:
                if key!='viscousbattleaxe':before[group+':'+key]=hashlib.sha256(blob).hexdigest()
        rebuilt=bytes([len(groups)])
        for group,items in groups:
            items=[(k,b) for k,b in items if k!='viscousbattleaxe']
            if group=='equipment':items.append(('viscousbattleaxe',entry))
            rebuilt+=group.encode()+b'\0'+struct.pack('>H',len(items))+b''.join(blob for _,blob in items)
        encoded=gzip.compress(rebuilt,mtime=0)
        if args.check:assert gzip.decompress(path.read_bytes())==rebuilt,name
        else:path.write_bytes(encoded)
        after={g+':'+k:hashlib.sha256(b).hexdigest() for g,items in archive(rebuilt) for k,b in items if k!='viscousbattleaxe'}
        assert before==after;preservation[name]=before
    emit('dev/myworld/battleaxe-coatings/archive-entry-hashes.json',json.dumps(preservation,indent=2)+'\n')
    geometry=['// Generated native geometry; edit coating manifest/source art.', 'package orsc;', 'import orsc.graphics.two.SpriteArchive.*;', 'import java.awt.image.BufferedImage;', 'import java.io.InputStream;', 'import javax.imageio.ImageIO;', 'public final class BattleaxeCoatingSprites {', ' private BattleaxeCoatingSprites() {}', ' private static final int[][] GEOMETRY={']
    for _,meta in held:geometry.append('  {%s},'%','.join(str(int(x)) for x in (*meta['crop'],meta['shift'],*meta['offset'],*meta['canvas'])))
    geometry+=[' };', ' public static Entry load() {', '  Entry entry=new Entry("viscousbattleaxe",Entry.TYPE.PLAYER_EQUIPPABLE_HASCOMBAT,Frame.LAYER.MAIN_HAND,18);', '  try { for(int n=0;n<18;n++) {', '   String relative="sprites/equipment/viscousbattleaxe/held-"+String.format(java.util.Locale.ROOT,"%02d",n)+".png";', '   BufferedImage image;', '   try(InputStream in=BattleaxeCoatingSprites.class.getResourceAsStream("/myworld-assets/"+relative)) {', '    if(in!=null) image=ImageIO.read(in); else image=ImageIO.read(new java.io.File("../dev/myworld/assets/"+relative));', '   }', '   int[] g=GEOMETRY[n]; Frame frame=new Frame(g[0],g[1],g[2]!=0,g[3],g[4],g[5],g[6]);', '   for(int y=0;y<g[1];y++) for(int x=0;x<g[0];x++) { int pixel=image.getRGB(x+(g[2]!=0?g[3]:0),y+(g[2]!=0?g[4]:0)); frame.getPixels()[y*g[0]+x]=(pixel>>>24)==0?0:pixel&0xFFFFFF; }', '   entry.getFrames()[n]=frame;', '  } return entry; } catch(java.io.IOException e) { throw new IllegalStateException("Coated battleaxe artwork is missing",e); }', ' }', '}']
    emit('Client_Base/src/orsc/BattleaxeCoatingSprites.java','\n'.join(geometry)+'\n')
    # Editable Aseprite authoring files use the same native canvases, not a
    # normalized animation sheet. PNGs remain the deterministic packer input.
    if not args.check:
        for path in images:
            dest=ROOT/authored/(path.stem+'.aseprite');dest.parent.mkdir(parents=True,exist_ok=True)
            subprocess.run(['aseprite','-b',str(ROOT/path),'--save-as',str(dest)],check=True,stdout=subprocess.DEVNULL)
    print('PASS coating manifest/catalog/native assets; 15 forms, 18 frames, untouched archive entries preserved')

if __name__=='__main__':main()
