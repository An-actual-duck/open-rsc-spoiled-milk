#!/usr/bin/env python3
"""Generate standalone client/server declarations from the canonical Cleric wire contract."""
from pathlib import Path
import argparse
root=Path(__file__).resolve().parents[1]
parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
source=(root/'tools/protocol/ClericBlessingContract.java').read_text()
for directory,package in [('server/src/com/openrsc/server/net/rsc','com.openrsc.server.net.rsc'),('Client_Base/src/orsc','orsc')]:
 path=root/directory/'ClericBlessingContract.java'
 text='// Generated by scripts/generate-cleric-blessing-contract.py; edit tools/protocol/ClericBlessingContract.java.\npackage '+package+';\n\n'+source
 if args.check:
  assert path.read_text()==text,'Stale Cleric contract: '+str(path)
 else:path.write_text(text)
print('PASS matching Cleric blessing protocol contracts')
