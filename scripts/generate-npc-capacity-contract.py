#!/usr/bin/env python3
"""Generate matching standalone server/client NPC contracts from one source."""
from pathlib import Path
import argparse
root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
source = (root / 'tools/protocol/NpcCapacityContract.java').read_text()
for directory, package in [('server/src/com/openrsc/server/net/rsc', 'com.openrsc.server.net.rsc'), ('Client_Base/src/orsc', 'orsc')]:
    path = root / directory / 'NpcCapacityContract.java'
    text = '// Generated by scripts/generate-npc-capacity-contract.py; edit tools/protocol/NpcCapacityContract.java.\npackage ' + package + ';\n\n' + source
    if args.check:
        if not path.exists() or path.read_text() != text:
            raise SystemExit('Stale NPC contract: ' + str(path))
    else:
        path.write_text(text)
print('PASS matching NPC capacity contracts')
