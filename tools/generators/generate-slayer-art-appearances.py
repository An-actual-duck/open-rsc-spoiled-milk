#!/usr/bin/env python3
"""Generate paired Slayer appearance tables after the current published aliases."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    data = json.loads((ROOT / 'tools/generators/slayer-art-appearances.json').read_text())
    entries = data['definitions']
    first = data['baseAnimationCount']
    if [e['appearanceId'] for e in entries] != list(range(first + 1, first + len(entries) + 1)):
        raise ValueError('Slayer appearance IDs must append without gaps')
    if len({e['itemId'] for e in entries}) != len(entries):
        raise ValueError('Duplicate Slayer item')
    rows = ',\n'.join(
        '        new Mapping(%d, %d, %d, "%s", 0x%06x, %s)' % (
            e['itemId'], e['appearanceId'], e['fallbackAppearance'], e['family'],
            e['mask'], str(e['hasCombat']).lower()) for e in entries)
    template = '''// Generated by tools/generators/generate-slayer-art-appearances.py. Do not edit.
package PACKAGE;

public final class SlayerArtAppearances {
    private SlayerArtAppearances() { }
    public static final int BASE_ANIMATION_COUNT = FIRST;
    public static final class Mapping {
        public final int itemId, appearanceId, fallbackAppearance, mask;
        public final String family;
        public final boolean hasCombat;
        private Mapping(int item, int appearance, int fallback, String family, int mask, boolean combat) {
            this.itemId = item; this.appearanceId = appearance; this.fallbackAppearance = fallback;
            this.family = family; this.mask = mask; this.hasCombat = combat;
        }
    }
    public static final java.util.List<Mapping> MAPPINGS = java.util.Collections.unmodifiableList(java.util.Arrays.asList(
ROWS
    ));
CLIENT_METHOD
}
'''.replace('FIRST', str(first)).replace('ROWS', rows)
    client_method = '''    public static void appendAnimations(java.util.List<com.openrsc.client.entityhandling.defs.extras.AnimationDef> animations) {
        if (!orsc.Config.S_WANT_CUSTOM_SPRITES) return;
        if (animations.size() != BASE_ANIMATION_COUNT)
            throw new IllegalStateException("Published animation prefix changed; review Slayer appearance allocation");
        for (Mapping entry : MAPPINGS) {
            if (animations.size() != entry.appearanceId - 1)
                throw new IllegalStateException("Slayer appearance ID drift");
            animations.add(new com.openrsc.client.entityhandling.defs.extras.AnimationDef(
                entry.family, "equipment", entry.mask, 0, entry.hasCombat, false, 0));
        }
    }
'''
    for package, directory, extra in [
        ('com.openrsc.client.entityhandling', 'Client_Base/src/com/openrsc/client/entityhandling', client_method),
        ('com.openrsc.server.external', 'server/src/com/openrsc/server/external', ''),
    ]:
        target = ROOT / directory / 'SlayerArtAppearances.java'
        text = template.replace('PACKAGE', package).replace('CLIENT_METHOD', extra)
        if args.check:
            if target.read_text() != text:
                raise ValueError('Stale generated appearance table: ' + str(target))
        else:
            target.write_text(text)
    print('PASS paired Slayer appearance tables' + (' are current' if args.check else ' generated'))


if __name__ == '__main__':
    main()
