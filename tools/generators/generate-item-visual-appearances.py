#!/usr/bin/env python3
"""Generate explicit paired appearance expectations without moving any catalog IDs."""
import argparse
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]

def main():
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    mappings=json.loads((ROOT/'tools/generators/item-visual-appearances.json').read_text())['mappings']
    assert len({m['itemId']for m in mappings})==len(mappings)
    rows=',\n'.join('        new Mapping(%d, %d, %d, "%s", 0x%06x)'%(m['itemId'],m['legacyAppearanceId'],m['appearanceId'],m['family'],m['mask'])for m in mappings)
    template='''// Generated by tools/generators/generate-item-visual-appearances.py. Do not edit.
package PACKAGE;
public final class ItemVisualAppearances {
    private ItemVisualAppearances() { }
    public static final class Mapping {
        public final int itemId, legacyAppearanceId, appearanceId, mask;
        public final String family;
        private Mapping(int item, int legacy, int appearance, String family, int mask) {
            itemId=item; legacyAppearanceId=legacy; appearanceId=appearance;
            this.family=family; this.mask=mask;
        }
    }
    public static final java.util.List<Mapping> MAPPINGS = java.util.Collections.unmodifiableList(java.util.Arrays.asList(
ROWS
    ));
}
'''.replace('ROWS',rows)
    for package,folder in [('com.openrsc.server.external','server/src/com/openrsc/server/external'),('com.openrsc.client.entityhandling','Client_Base/src/com/openrsc/client/entityhandling')]:
        path=ROOT/folder/'ItemVisualAppearances.java';text=template.replace('PACKAGE',package)
        if args.check:assert path.read_text()==text,'Stale visual appearance expectations: '+str(path)
        else:path.write_text(text)
    print('PASS explicit paired visual appearance expectations')
if __name__=='__main__':main()
