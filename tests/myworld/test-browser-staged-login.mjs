import assert from 'node:assert/strict';
import {createStagedLoginGate} from '../../tools/browser-gameplay/web/browser-staged-login.js';
import {repeatableFixturePolicy} from '../../tools/browser-gameplay/web/browser-repeatable-policy.js';
const gate=createStagedLoginGate({enabled:true});
const proof={completedFrame:12,worldReady:true,coverageReady:true,cpuReady:true,blocked:false,error:false};
assert.equal(gate.blocked,false);gate.begin(1,12);assert.equal(gate.blocked,true);
assert.equal(gate.ready(1,proof),false,'old completed frame is insufficient');
for(const key of ['worldReady','coverageReady','cpuReady'])assert.equal(gate.ready(1,{...proof,completedFrame:13,[key]:false}),false,key);
assert.equal(gate.ready(1,{...proof,completedFrame:13,blocked:true}),false);
assert.equal(gate.ready(1,{...proof,completedFrame:13,error:true}),false);
assert.equal(gate.ready(2,{...proof,completedFrame:13}),false);
assert.throws(()=>gate.finish(1,true),/Unprepared/);
assert.equal(gate.ready(1,{...proof,completedFrame:13}),true);gate.finish(1,true,18);
assert.equal(gate.blocked,true,'commit alone must not release the input cover');
gate.observe('LOGIN',{...proof,completedFrame:19});assert.equal(gate.blocked,true);gate.observe('GAME',{...proof,worldReady:false,completedFrame:19});assert.equal(gate.blocked,true);
gate.observe('GAME',{...proof,completedFrame:18});assert.equal(gate.blocked,true,'pre-COMMIT frame cannot release the cover');
gate.observe('GAME',{...proof,completedFrame:19,blocked:true});assert.equal(gate.blocked,true);
gate.observe('GAME',{...proof,completedFrame:19});assert.equal(gate.blocked,false);
gate.begin(2,20);gate.finish(1,false);assert.equal(gate.stats.phase,'preparing');
assert.equal(gate.ready(1,{...proof,completedFrame:30}),false);assert.throws(()=>gate.begin(1,20));
gate.finish(2,false);assert.equal(gate.blocked,false);gate.dispose();assert.equal(gate.ready(2,proof),false);
assert.deepEqual(Object.keys(gate.stats).sort(),['approved','enabled','owner','phase','requiredFrame'],'no account/token/destination in JS gate');
assert.throws(()=>createStagedLoginGate().begin(1,0));
