	final Sprite symbol;
	final String keyLabel;

	MinimapMarkerIcon(String keyLabel, int color, String... rows) {
		this.keyLabel = keyLabel;
		int width = rows[0].length();
		int[] pixels = new int[width * rows.length];
		for (int y = 0; y < rows.length; y++) {
			for (int x = 0; x < width; x++) {
				if (rows[y].charAt(x) == '#') pixels[y * width + x] = color;
			}
		}
		symbol = new Sprite(pixels, width, rows.length);
	}
